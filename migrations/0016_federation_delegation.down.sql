-- تراجع الهجرة 0016.
--
-- **يُعيد الحالَ إلى ترابٍ لا سلطةَ له مقروءةً في القاعدة:** بسقوط الجداول
-- الثلاثة يعود «الإقليمُ المستقلُّ» فقرةً في وثيقةٍ لا تُوقف فعلاً ولا تُثبته،
-- ولا يبقى في الحالةِ المحفوظةِ أثرٌ لفعلٍ مُورس محليّاً ولا لرفضٍ وقع.
--
-- ومحوُ الرفوضِ محوُ **مادّةِ مراجعةِ العزل** نفسِها: يصير الترابُ الذي تجاوز
-- حدَّه كأنّه لم يتجاوز، ويصير سحبُ التفويضِ الذي أوقف عملاً كأنّه لم يُوقف
-- شيئاً — وذاك أخطرُ من الفقدان، لأنّ الحدَّ الذي يُمحى أثرُه يُتجاوز بلا أثر.
-- ومحوُ الأفعالِ المحليةِ محوُ الدليلِ على أنّ الترابَ عمل بنفسه، وبذلك لا يبقى
-- ما يُقاس عليه معيارُ قبولِ الخطوة.
--
-- ولذلك يُشترط ألّا يكون في الجدولين فعلٌ مُمارَسٌ ولا رفضٌ مسجَّل. وصفوفُ
-- التفويضِ وحدَها ليست وقائعَ نهائيةً — تُعاد بالإنفاذ من الوثيقة نفسِها — فلا
-- تمنع التراجع. أمّا صفٌّ **مسحوبُ** التفويضِ فقيدُه سببٌ مكتوبٌ يُفقَد بالإسقاط،
-- وهو مذكورٌ هنا لا مسكوتٌ عنه: من أراد حفظَه فليصدّره قبل التراجع.

DO $$
DECLARE recorded bigint;
BEGIN
  SELECT
    (SELECT count(*) FROM state.federation_refusals)
    + (SELECT count(*) FROM state.federation_local_acts)
  INTO recorded;

  IF recorded > 0 THEN
    RAISE EXCEPTION
      'تراجع الهجرة 0016 موقوف: % واقعةً نهائيةً مسجَّلةً (أفعالٌ ترابيةٌ مُورست أو رفوضٌ سُجِّلت). إسقاطُ الجداول يمحو دليلَ استقلالِ الإقليمِ ومادّةَ مراجعةِ عزله، فيصير المتجاوِزُ كأنّه لم يتجاوز. صدّرها (scripts/backup.mjs) ثم أعِد التراجع.',
      recorded;
  END IF;
END $$;

DROP INDEX state.federation_refusals_territory_idx;
DROP INDEX state.federation_local_acts_territory_idx;
DROP INDEX state.federation_delegations_parent_idx;

DROP TABLE state.federation_refusals;
DROP TABLE state.federation_local_acts;
DROP TABLE state.federation_delegations;
