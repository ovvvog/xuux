-- هجرة 0020 — سجلُّ سحبِ الشهاداتِ الدائمُ (Grok-F03).
--
-- كان سحبُ الشهاداتِ في الذاكرةِ وحدَها (`Set` في `CertificateAuthority`)، فلا يبقى
-- أثرُ السحبِ بعدَ إعادةِ تشغيلٍ: شهادةٌ سُحبت تعود صالحةً لأنّ مجموعةَ السحبِ
-- فارغةٌ في العمليةِ الجديدةِ والتوقيعُ ما زال صحيحاً. وبلا انتهاءِ صلاحيّةٍ
-- تبقى الشهادةُ المسروقةُ صالحةً إلى الأبدِ ما لم تُسحب في نفسِ العمليةِ الحيّةِ.
--
-- هذه الهجرةُ تُثبِّتُ سجلَّ السحبِ على القرصِ: كلُّ شهادةٍ تُسحبُ تُكتَبُ هنا،
-- ويُحمَّلُ هذا الجدولُ قبلَ أيِّ `isValid`، فلا تعودُ شهادةٌ مسحوبةٌ صالحةً
-- بعدَ إعادةِ الإقلاعِ. والجدولُ **لا يُحذفُ منه** في وقتِ التشغيلِ — السحبُ
-- أحاديُّ الاتجاهِ لا يُلغى، فإبطالُ شهادةٍ قرارٌ لا تراجعَ عنه إلّا بإصدارِ
-- شهادةٍ جديدةٍ بمعرّفٍ مختلف. وكلُّ الأعمدةِ `NOT NULL` فلا يُقبلُ سحبٌ بلا
-- سببٍ ولا بلا مسؤولٍ ولا بلا وقتٍ.

CREATE TABLE state.certificate_revocations (
  certificate_id text PRIMARY KEY
    CHECK (length(btrim(certificate_id)) > 0),
  revoked_by text NOT NULL
    CHECK (length(btrim(revoked_by)) > 0),
  reason text NOT NULL
    CHECK (length(btrim(reason)) > 0),
  revoked_at timestamptz NOT NULL DEFAULT now()
);

-- لا فهرسَ إضافيَّ: المفتاحُ الأساسيُّ هو معرّفُ الشهادةِ، وهو ما يُفحَصُ في
-- كلِّ `isValid`. والجدولُ صغيرٌ (عددُ الشهاداتِ المسحوبةِ، لا كلُّ الشهاداتِ)،
-- فلا حاجةَ إلى فهرسٍ على `revoked_at` للقراءةِ المتكرّرةِ.

-- منعُ الحذفِ في وقتِ التشغيلِ: لا مسارَ تطبيقيٌّ يستدعي `DELETE` على هذا
-- الجدولِ، والسحبُ أحاديُّ الاتجاهِ. وهذا القيدُ توثيقيٌّ لا قابلٌ للإلزامِ
-- على مستوى SQL (إذ قد يحتاجُ المديرُ إلى ترحيلٍ)، لكنَّ التطبيقَ لا يُصدِرُ
-- حذفاً أبداً.
