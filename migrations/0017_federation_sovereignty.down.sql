-- تراجع الهجرة 0017.
--
-- **يُعيد الحالَ إلى سيادةٍ لا تُراجَع:** بسقوطِ الجدولِ يعود التفويضُ وسحبُه
-- حالةً حاضرةً في صفٍّ يُحدَّث في موضعه، فلا يُعرَف **بأيِّ أمرٍ ملكيٍّ** فُوِّض
-- ترابٌ ولا بأيِّ أمرٍ سُحب، ولا يبقى قياسٌ واحدٌ لزمنِ نفاذِ سحبٍ — وهو نفسُه
-- معيارُ قبولِ الخطوة M8.08. ويصير «السحبُ ينفذ خلال مهلةٍ معلَنة» دعوىً بلا
-- عمودٍ يشهد لها.
--
-- وأخطرُ من الفقدان أنّ محوَ السجلِّ يمحو **الدليلَ على التأخُّر**: سحبٌ نفَذ
-- متجاوِزاً مهلتَه يصير كأنّه نفَذ فيها، إذ لا يبقى إلا صفُّ تفويضٍ يقول إنّه
-- مسحوبٌ ولا يقول متى أُمِر بسحبه. فالمهلةُ التي يُمحى قياسُها تُتجاوز بلا أثر.
--
-- ولذلك يُشترط ألّا يكون في السجلِّ صفٌّ واحد. وصفوفُه **وقائعُ نهائيةٌ** لا
-- تُعاد بالإنفاذ من وثيقةٍ: وقتُ إصدارِ أمرٍ ملكيٍّ ماضٍ ومعرّفُه وزمنُه المقيسُ
-- لا يُشتقُّ أيٌّ منها من `config/federation-delegation.yaml`.

DO $$
DECLARE recorded bigint;
BEGIN
  SELECT count(*) FROM state.federation_delegation_register INTO recorded;

  IF recorded > 0 THEN
    RAISE EXCEPTION
      'تراجع الهجرة 0017 موقوف: % أمراً ملكيّاً منفَّذاً مسجَّلاً في سجلِّ التفويضاتِ النافذة. إسقاطُ الجدول يمحو معرّفاتِ الأوامرِ وأوقاتَ إصدارها وقياسَ زمنِ نفاذها، فيصير سحبٌ تجاوز مهلتَه كأنّه نفَذ فيها. صدّرها (scripts/backup.mjs) ثم أعِد التراجع.',
      recorded;
  END IF;
END $$;

DROP INDEX state.federation_register_overdue_idx;
DROP INDEX state.federation_register_territory_idx;

DROP TABLE state.federation_delegation_register;
