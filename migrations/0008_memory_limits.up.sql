-- الهجرة 0008 — انتهاء ذاكرة الوكلاء قيداً في القاعدة (الخطوة M7.05).
--
-- العيب الذي تعالجه: العمود `state.memories.expires_at` قائمٌ منذ الهجرة `0001`،
-- وسياسة الاحتفاظ في الكود تقول `endsBy: 'expires_at'` — و`AgentMemoryStore.remember`
-- **لم يكتب هذا العمود ولا مرّةً واحدة**. فكل ذاكرةٍ كُتبت أبديّة، ودورةُ المحو
-- تمرّ على صفر صفوف ثم تُعلن نجاحها. وهذا أسوأ من غياب المحو: غيابٌ يُقرأ حضوراً.
--
-- والقيد هنا هو الضمان الأخير، يعمل حتى لو كتب أحدٌ في الجدول من غير طريق المخزن
-- (نصٌّ يدوي، أو مسارٌ مستقبلي يُنسى فيه العمود كما نُسي مرّة): مدخلٌ بلا تاريخ
-- انتهاء **يُرفض**، والاستثناء الوحيد الحفظُ القانوني — والقيد القائم
-- `memories_hold_has_no_expiry` يمنع أن يحمل المحفوظُ قانوناً تاريخَ انتهاء، فصار
-- القيدان معاً تلازماً: إمّا انتهاءٌ وإمّا حفظٌ قانوني، ولا ثالث.
--
-- **وتوقّفٌ قبل التغيير لا تصحيحٌ صامت:** صفوفٌ قائمة بلا انتهاء ولا حفظٍ قانوني
-- لا يعرف المُهاجر مدّتها — فمدّةٌ يخترعها هي سياسةُ احتفاظٍ يكتبها من لا يملكها،
-- وحذفُها محوُ بياناتٍ لا ترحيل. فيتوقّف ويُسمّي العدد ويطلب مرور المطهِّر
-- (`AgentMemoryStore.sweepExpired`) أو إعلانَ الحفظ القانوني عليها.
--
-- ولا `BEGIN`/`COMMIT` هنا: المُهاجر يفتح المعاملة بنفسه، و`COMMIT` داخل الملف
-- كان سيُثبّت المعاملة الخارجية قبل صفّها في `schema_migrations`.
--
-- **حدٌّ معلَن لا يُنفَّذ في هذه الهجرة:** حصّة الوكيل (عدداً وبايتات) وحدُّ حجم
-- المدخل الواحد مفروضةٌ في الكود (`src/data/memory-limits.mjs`) لا في القاعدة.
-- فرضُها هنا يقتضي إمّا مُحرِّضاً يعدّ صفوف الوكيل عند كل إدراج — وهو قفلٌ على
-- الجدول في كل كتابة — وإمّا قيد `CHECK` على `pg_column_size` وهي دالّةٌ غير
-- معلَنة الثبات فقد يرفضها القيد. ولم تتوفّر قاعدةٌ تشغيلية لقياس أيّهما في هذه
-- الخطوة، فلم يُكتب ما لا يُقاس، وهو مسجَّل في `docs/REMAINING_WORK.md`.

DO $$
DECLARE
  eternal bigint;
BEGIN
  SELECT count(*) INTO eternal
  FROM state.memories
  WHERE expires_at IS NULL AND NOT legal_hold;

  IF eternal > 0 THEN
    RAISE EXCEPTION
      'الترحيل 0008 متوقّف: % صفّاً في state.memories بلا تاريخ انتهاء ولا حفظ قانوني. مدّةٌ يخترعها المُهاجر سياسةُ احتفاظٍ يكتبها من لا يملكها، وحذفُ الصفوف محوُ بيانات لا ترحيل. امنحها تاريخ انتهاء بمسار الكود أو أعلِن عليها الحفظ القانوني ثم أعِد الترحيل.',
      eternal;
  END IF;
END
$$;

ALTER TABLE state.memories
  ADD CONSTRAINT memories_expiry_required CHECK (expires_at IS NOT NULL OR legal_hold);

-- فهرسٌ على (الوكيل، الانتهاء): المطهِّر يسأل «ما انتهى لهذا الوكيل»، وحصّةُ
-- الوكيل تُقاس بصفوفه وحدها. والفهرس القائم `memories_expiry_idx` على الانتهاء
-- وحده يخدم المسح العامّ لا المسح لوكيل.
CREATE INDEX memories_agent_expiry_idx ON state.memories (agent_id, expires_at);

COMMENT ON COLUMN state.memories.expires_at IS
  'تاريخ انتهاء المدخل، يُحسب من config/memory.yaml عند الكتابة لا من الطلب (M7.05). فراغه مأذونٌ فقط مع الحفظ القانوني، ويفرضه القيدان memories_expiry_required وmemories_hold_has_no_expiry معاً.';
