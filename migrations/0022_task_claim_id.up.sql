-- الهجرة 0022 — معرِّفُ الحجزِ (`claim_id`) لهويةِ نتيجةٍ لا يُعادُ استعمالُها (`WL-392`).
--
-- **العيبُ الذي تعالجه، بنصِّه كما في سجلِّ الديون (`LIVE-45`/ب):** تسويةُ نتيجةٍ
-- معلّقةٍ كانت تُقيَّدُ بهويةٍ قابلةٍ لإعادةِ الاستعمالِ — (المهمّة، العامل، عدّادُ
-- المحاولاتِ). فالمساراتُ التي تُرجِعُ العدّادَ (`releaseUnstarted` و`releaseForHalt`)
-- تُخرجُ المهمّةَ من `running` ثمّ يعودُ الحجزُ بالاسمِ نفسِهِ إلى العدّادِ نفسِهِ:
-- حجزانِ مختلفانِ بهويةٍ واحدةٍ نصّاً. فنتيجةُ الحياةِ الأولى كانت ستُسوّى فوقَ حجزِ
-- الحياةِ الثانيةِ لا بجُرمِ توقيتٍ بل لأنّ الهويةَ صُوِّرتْ واقفةً وهي تعودُ.
--
-- **الحلُّ:** معرِّفٌ جديدٌ لكلِّ حجزٍ (`claim_id`) يُولَدُ عندَ الحجزِ وحدَه، تحملهُ
-- النتيجةُ المُخزَّنةُ والتسويةُ ومفتاحُ الاستيفاءِ، ويُتحقَّقُ منه داخلَ كتابةِ
-- النتيجةِ نفسِها (`succeed`). فحجزٌ جديدٌ — ولو بالمهمّةِ والاسمِ والعدّادِ
-- نفْسِها — معرِّفُهُ جديدٌ فلا تُقبلُ عليه نتيجةُ حياةٍ سابقة.
--
-- **والفراغُ مُعلَّنٌ لا مستورٌ:** العمودُ فارغٌ لكلِّ مهمّةٍ غيرِ محجوزةٍ (لم
-- تُحجز بعدُ) أو فُكَّ حجزُها بلا حصيلةٍ نهائيةٍ (إرجاعٌ: `releaseUnstarted` و
-- `releaseForHalt` وإعادةُ الطابورِ في `fail`/`reclaim`) — وكلُّ مسارٍ يمسكُ العقدَ
-- يمسكُ المعرِّفَ معَه. **أمّا الحصيلةُ النهائيةُ فتحتفظُ به دليلًا**: النجاحُ
-- والفشلُ النهائيُّ والإلغاءُ تُبقي معرِّفَ الحجزِ الذي أنتجَها مقروءًا في
-- الصفِّ، فهو هويةُ النتيجةِ التي تُقارنُ بها التسويةُ عندَ الإقلاعِ (بصمةٌ
-- من حياةِ السجلِّ نفسِها أم من حياةٍ أحدث). والقيدُ في القاعدةِ لا في الكودِ
-- (نفسُ فلسفةِ `0004`): `tasks_running_needs_claim` يُلزمُ المهمّةَ الجاريةَ
-- بمعرِّفِ حجزٍ قائمٍ، فلا حالةَ وسيطةً — مهمّةٌ جاريةٌ بلا هويةِ حجزٍ — حتى لو
-- عبثَ كاتبٌ بمسارِ الإمساك.
--
-- **وحدٌّ مُعلَنٌ:** المعرِّفُ لا يُثبِتُ وحدانيةَ اسمِ العاملِ (الدَّينُ `LIVE-45`/د):
-- عاملانِ بالاسمِ نفسِهِ يولِّدانِ حجزَينِ بمعرِّفَينِ مختلفَينِ، فالتسويةُ تفرِّقُ
-- بينَهما — وهذا يُخفِّفُ الدَّينَ ولا يُغلِقُه.

ALTER TABLE state.tasks ADD COLUMN claim_id uuid;

-- صفوفٌ جاريةٌ قائمةٌ قبلَ هذه الهجرةِ: العمودُ وُلدَ فارغاً لها، والقيدَ أدناهِ
-- يرفضُها فوراً لو لم تُعالَج. فكلُّ حجزٍ قائمٍ يُعطى معرِّفاً مستقلاً — لا
-- يُشتركُ فيه حجزانِ ولا يُفترضُ أحدُها — وهذا لا يُنسبُ إلى حياةٍ ماضيةٍ ولا
-- يزعمُ معرِّفَها (النتائجُ المعلّقةُ لم تكن موجودةً قبلَ هذه الهجرةِ أصلاً، فلا
-- سجلَّ يُقارَنُ به). وهذا إصلاحُ الهجرةِ على قاعدةٍ قائمةٍ واختبارُه محليٌّ —
-- لا تفويضٌ لتطبيقِها على إنتاجٍ حيٍّ (ذاك مسارُ التفويضِ الخاصُّ به).
UPDATE state.tasks SET claim_id = gen_random_uuid() WHERE claim_id IS NULL AND state = 'running';

ALTER TABLE state.tasks
  ADD CONSTRAINT tasks_running_needs_claim CHECK (
    state <> 'running' OR claim_id IS NOT NULL
  );

COMMENT ON COLUMN state.tasks.claim_id IS
  'معرِّفُ الحجزِ الحيِّ وحدَه: يُولَدُ عندَ الحجزِ ويُفرَغُ عندَ فكِّه، وتُقيَّدُ به نتيجةُ المُعالِجِ فلا تُسوّى فوقَ حجزٍ أحدثَ بهويةٍ مُعادِ استعمالِها.';
