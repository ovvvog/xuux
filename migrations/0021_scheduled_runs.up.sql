-- الهجرة 0021 — دفترُ الإطلاقاتِ المُجدوَلةِ (إغلاقُ الدَينِ `D-4`، `WL-191`).
--
-- **العيبُ الذي تعالجُه، بنصِّه كما كان في سجلِّ الدَينِ:** «لا مُجدوِلَ ذاتيَّ
-- التشغيلِ في المستودعِ. التقاريرُ والتمارينُ تُطلَقُ بنداءٍ يدويٍّ، والدوريّةُ
-- عهدٌ في وثيقةٍ لا فعلٌ يقعُ». ومعيارُ الإغلاقِ نصُّه «مُجدوِلٌ يُطلِقُ التقاريرَ
-- والتمارينَ بلا نداءٍ يدويٍّ، **مقيسٌ بواقعةٍ في دفترٍ**» — وهذا الجدولُ هو ذاك
-- الدفترُ. وبلا جدولٍ على القرصِ يكونُ «آخرُ تشغيلٍ» متغيِّراً في عمليّةٍ: تعودُ
-- إعادةُ التشغيلِ فتُطلِقُ عملاً وقعَ قبلَ دقيقةٍ، ولا يبقى بعدَ ساعةٍ ما يقولُ
-- إنّه وقعَ مرّتَينِ.
--
-- **وقفلُ الشقِّ قيدٌ هنا لا شرطٌ في الكودِ:** `scheduled_runs_slot_phase_unique`
-- يجعلُ إطلاقَ الشقِّ نفسِه مرّتَينِ **مستحيلاً** ولو عملت نسختانِ من المُجدوِلِ
-- على قاعدةٍ واحدةٍ؛ الثانيةُ تفشلُ بتضاربٍ مُسمّى من المستودعِ لا بكتابةٍ
-- مزدوجةٍ صامتةٍ. وشرطٌ في الكودِ («اقرأْ ثمّ اكتبْ») يمرُّ منه سباقٌ بين نسختَينِ
-- بلا أثرٍ يُقرأُ لاحقاً — ولهذا القيدُ في القاعدةِ لا في الفحصِ.
--
-- **والأطوارُ ثلاثةٌ لا اثنانِ:** `dispatched` يُكتَبُ **قبلَ** تشغيلِ العملِ،
-- ثمّ `completed` أو `failed` بعدَه. وثلاثةُ أطوارٍ تُفرِّقُ ما لا يُفرَّقُ بطورَينِ:
-- عملٌ نجحَ، وعملٌ فشلَ، وعملٌ **انقطعَ في منتصفِه** (حجزٌ بلا نتيجةٍ). وقراءةُ
-- الموعدِ تعتمدُ `completed` وحدَه، فانقطاعٌ لا يُقرأُ نجاحاً ولا يُعيدُ الشقَّ.
--
-- **و`slot_at` نصٌّ لا `timestamptz`:** هو **مُعرِّفُ الشقِّ** لا لحظةَ حدثٍ،
-- ويدخلُ في التجزئةِ. وفرقُ الدقّةِ بين ساعةِ القاعدةِ (ميكروثانية) و`Date`
-- (ميليثانية) كان يكسرُ السلسلةَ على البريءِ — انحرافٌ سقطَ فيه المشروعُ في
-- `M3.05` وتكرّرَ حسمُه في دفترَي النسبِ والمحوِ (`0007`، `0009`). ونصُّ الشقِّ
-- مقيَّدٌ بنمطِ ISO كي لا يصيرَ القفلُ نصّاً حرّاً يُكتَبُ بصيغتَينِ فيُفتَحُ
-- الشقُّ مرّتَينِ.
--
-- **ولا مرجعَ إلى جدولِ فاعلينَ في `actor_id`:** الفاعلُ مُثبَتٌ في سجلِّ جذرِ
-- الثقةِ لحظةَ الإطلاقِ، ومرجعٌ يمنعُ سحبَ هويةٍ أو يُسقِطُ شاهدَ إطلاقٍ وقعَ —
-- وكلاهما نقضٌ لغرضِ الدفترِ. فالمعرِّفُ نصٌّ محفوظٌ، والنسبةُ محفوظةٌ بالسلسلةِ.
--
-- **حدٌّ معلَنٌ:** السلسلةُ **واحدةٌ للدفترِ كلِّه** لا سلسلةٌ لكلِّ عملٍ، فـ`seq`
-- فريدٌ عامٌّ. وأثرُ ذلك أنّ نبضتَينِ متوازيتَينِ تتنافسانِ على نفسِ الرقمِ وتفشلُ
-- إحداهما بتضاربٍ مُسمّى — وهو المطلوبُ (لا يُطلِقُ مُجدوِلانِ معاً) لا عيبٌ.
--
-- **حدٌّ معلَنٌ ثانٍ:** لا مُحرِّضَ يمنعُ `UPDATE`/`DELETE` على هذا الدفترِ،
-- لنفسِ سببِ `0009`: منعُه يقتضي مُحرِّضاً بصلاحيةِ مالكِ الجدولِ، ولا تُثبَّتُ
-- صلاحيةٌ لم تُقَسْ في بيئةٍ بلا قاعدةٍ تشغيليّةٍ. والكشفُ قائمٌ لا المنعُ:
-- `ScheduledRunLedger.verify()` يُظهرُ أيَّ تعديلٍ أو حذفٍ لانقطاعِ السلسلةِ،
-- وقيودُ التفرّدِ أدناه تمنعُ الإدراجَ المزدوجَ. وهو مسجَّلٌ في
-- `docs/REMAINING_WORK.md`.
--
-- ولا `BEGIN`/`COMMIT` هنا: المُهاجِرُ يفتحُ المعاملةَ بنفسِه.

CREATE TABLE state.scheduled_runs (
  id state.entity_id PRIMARY KEY,
  -- معرِّفُ العملِ كما هو معلَنٌ في `config/schedule.yaml` (`job:<اسم>`).
  job_id text NOT NULL CHECK (job_id ~ '^job:[a-z0-9-]+$'),
  -- مُعرِّفُ الشقِّ: بدايةُ النافذةِ محسوبةً على شبكةٍ ثابتةٍ من مبدأِ الزمنِ.
  slot_at text NOT NULL CHECK (
    slot_at ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}\.[0-9]{3}Z$'
  ),
  phase text NOT NULL,
  actor_id text NOT NULL CHECK (length(btrim(actor_id)) > 0),
  -- السياسةُ التي أجازت الإطلاقَ؛ و`none` حين يسمحُ التركيبُ بقرارٍ بلا سياسةٍ
  -- مُسمّاةٍ — تُكتَبُ صريحةً لا تُترَكُ فراغاً يُقرأُ «لم يُسجَّلْ».
  decision_id text NOT NULL CHECK (length(btrim(decision_id)) > 0),
  detail jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(detail) = 'object'),
  seq integer NOT NULL CHECK (seq >= 1),
  recorded_at text NOT NULL CHECK (
    recorded_at ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}\.[0-9]{3}Z$'
  ),
  prev_hash text NOT NULL CHECK (prev_hash = 'genesis' OR prev_hash ~ '^[0-9a-f]{64}$'),
  hash text NOT NULL CHECK (hash ~ '^[0-9a-f]{64}$'),
  version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT scheduled_runs_phase_known CHECK (phase IN ('dispatched', 'completed', 'failed')),
  CONSTRAINT scheduled_runs_chain_linked CHECK ((seq = 1) = (prev_hash = 'genesis')),
  CONSTRAINT scheduled_runs_hash_unique UNIQUE (hash),
  CONSTRAINT scheduled_runs_seq_unique UNIQUE (seq),
  -- **قفلُ الشقِّ**: طورٌ واحدٌ لكلِّ (عملٍ، شقٍّ). حجزٌ ثانٍ لشقٍّ محجوزٍ يفشلُ
  -- في القاعدةِ، فلا إطلاقَ مزدوجاً ولو تعدّدت النسخُ.
  CONSTRAINT scheduled_runs_slot_phase_unique UNIQUE (job_id, slot_at, phase)
);

COMMENT ON TABLE state.scheduled_runs IS
  'دفترُ الإطلاقاتِ المُجدوَلةِ: موعدُ العملِ يُقاسُ من آخرِ شقٍّ مكتملٍ هنا لا من ذاكرةِ عمليّةٍ، وقفلُ الشقِّ يمنعُ إطلاقاً مزدوجاً.';

-- الاستعلامُ يمشي بترتيبِ السلسلةِ (للفحصِ) وبالعملِ (لقراءةِ الموعدِ).
CREATE INDEX scheduled_runs_seq_idx ON state.scheduled_runs (seq);
CREATE INDEX scheduled_runs_job_slot_idx ON state.scheduled_runs (job_id, slot_at DESC);
