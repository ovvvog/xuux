-- **يفقد بياناً بإعلانه:** كل صفوف نسب البيانات تُحذف — أصلُ كل أصل ومن حوّله
-- ومن قرأه ومن كتب فيه، وسلسلةُ التجزئة التي تكشف العبث بها. ومن أراد الاحتفاظ
-- فليأخذ نسخة (`npm run backup`) قبل التراجع.
--
-- ويُعاد عمود الادّعاء `state.data_assets.lineage` كما كان في `0002` — فارغاً
-- افتراضاً لكل صفّ. والصفوف المحذوفة **لا تُحوَّل** إليه: صفٌّ فيه معرّف سلفٍ
-- محقَّق وتجزئةٌ مرتبطة ليس هو نصّاً حرّاً في مصفوفة، وحشوُه هناك كان سيبدو
-- نسباً وهو ادّعاءٌ استعاد شكله بعد سقوط قيده.
--
-- الفهارس والقيود تسقط بسقوط الجدول، فلا تُحذف صراحةً.

DROP TABLE state.data_lineage;

ALTER TABLE state.data_assets
  ADD COLUMN lineage jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(lineage) = 'array');
