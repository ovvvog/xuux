-- الهجرة 0023 — سجلُّ إقلاعِ العمالِ: قيدُ تفرُّدِ الاسمِ للعاملِ الحيِّ (إغلاقُ
-- الدَّينِ `LIVE-45`/د — `WL-394`).
--
-- **العيبُ الذي تعالجه، بنصِّه كما في سجلِّ الديون:** «فرادةُ اسمِ العاملِ عقدٌ
-- لا قيدٌ: عاملانِ باسمٍ واحدٍ يُبطلانِ ضمانَ "لم يبدأ" في `releaseUnstarted`».
-- وبيانُ العطبِ: `releaseUnstarted` يُفرِجُ مهمّةً حُجزت بعدَ لحظةِ إقلاعِ
-- العمليةِ (`claimedAfter`) بذرّيّةِ `FOR UPDATE`، لأنّ حجزَ الحياةِ السابقةِ
-- للاسمِ نفسِه لا يُفرَج عنه (قد بدأه). وهذا الحكمُ يصحُّ **بعاملٍ واحدٍ
-- للاسمِ**: أمّا عاملانِ حيّانِ بالاسمِ نفسِه فالثاني يُفرِجُ حجزَ الأوّلِ
-- **وقد بدأ مُعالِجُه فعلًا** — فيُعادُ إلى الطابورِ وتُستأنفُ المحاولةُ فوقَ
-- تنفيذٍ جارٍ: ضمانُ «مرّةً على الأقلّ» نفسُه يُنقَضُ لا في النظريةِ بل
-- بمسارٍ مُسمّى في الإنتاجِ.
--
-- **والحلُّ قيدٌ في القاعدةِ لا فحصٌ في الكودِ** (نفسُ فلسفةِ `0004`
-- و`scheduled_runs_slot_phase_unique`): عمليّةٌ تُقلعُ باسمِ عاملٍ يُثبِتُ
-- ملكيّتَه للاسمِ **بذات المعاملةِ الذرّيّةِ**، فعمليّتانِ متزامنتانِ على الاسمِ
-- نفسِه تفشلُ إحداهما بتضادٍّ مُسمّى من القاعدةِ لا بكتابةٍ مزدوجةٍ صامتةٍ.
-- `ON CONFLICT (name) DO UPDATE ... WHERE` ذرّيٌّ في PostgreSQL: شرطُ
-- الاستبدالِ (تقادُمُ نبضةِ المالكِ الحاليّ) يُقيَّمُ على الصفِّ المقفولِ، فلا
-- يمرُّ سباقُ «قرأتُ ثمّ كتبتُ» بينَ إقلاعَينِ متزامنَينِ.
--
-- **والحياةُ عقدٌ ينتهي لا حالةٌ تُفحص:** النبضةُ (`heartbeat_at`) تُمدَّدُ في كلِّ
-- دورةِ عاملٍ، فغيابُها فوقَ عتبةٍ (`ttlMs` — إعدادُ الإقلاعِ) معناه موتُ
-- حاملِ الاسمِ أو انقطاعُه، ويملكُ الإقلاعُ الجديدُ الاسمَ **بأخذٍ صريحٍ
-- مُسجَّلٍ** لا بفحصٍ عابرٍ. والانقطاعُ الطويلُ (`WL-387`) لا يفتحُ الاسمَ
-- لغيرِ صاحبهِ إلا بعدَ العتبةِ — فلا يُعزَلُ عاملٌ حيٌّ عن اسمهِ بعَطَلةِ قاعدةٍ
-- عابرةٍ.
--
-- **وكلُّ أعمدةِ الجدولِ NOT NULL:** لا حالَةَ وسيطةً — صفٌّ بلا نبضةٍ أو بلا
-- مُعرِّفِ إقلاعٍ لا معنى له. والمفتاحُ الأوّليُّ `name` هو عينُ القيدِ:
-- صفٌّ واحدٌ للاسمِ الواحدِ، والملكيّةُ تُقرأُ من `boot_id`.
--
-- **وهذا الجدولُ سجلُّ حياةٍ لا سجلُّ تدقيقٍ:** التدقيقُ الكاملُ (من أقلعَ ومتى
-- ولماذا رُفضَ) مقرُّه سجلُّ العاملِ الدائمُ المختومُ (`kernel.worker.boot-*`
-- في `config/events.yaml`)، فلا تُكرَّرُ هنا آثارٌ حسّاسةٌ. والجدولُ يُحذفُ
-- منهُ عندَ التوقّفِ السليمِ (`deregister`) فلا يبقى شاهدَ قبرٍ يقرؤهُ فاحصٌ
-- قديمٌ.

CREATE TABLE state.worker_registrations (
  name text PRIMARY KEY,
  boot_id uuid NOT NULL,
  booted_at timestamptz NOT NULL,
  heartbeat_at timestamptz NOT NULL
);

COMMENT ON TABLE state.worker_registrations IS
  'ملكيّةُ اسمِ العاملِ الحيِّ: إقلاعٌ واحدٌ يملكُ الاسمَ حتى توقّفِهِ أو تقادُمِ نبضتِهِ؛ عاملانِ بالاسمِ نفسِه يُبطلانَ ضمانَ "لم يبدأ" في releaseUnstarted.';
COMMENT ON COLUMN state.worker_registrations.name IS
  'اسمُ العاملِ كما في lease_owner — المفتاحُ الأوّليُّ: صفٌّ واحدٌ للاسمِ.';
COMMENT ON COLUMN state.worker_registrations.boot_id IS
  'مُعرِّفُ الإقلاعِ الذي يملكُ الاسمَ: يُولَّدُ عندَ كلِّ إقلاعٍ، فتسويةُ النتائجِ والموتُ يُنسبانِ إلى حياةٍ بعينِها لا إلى الاسمِ العاري.';
COMMENT ON COLUMN state.worker_registrations.booted_at IS
  'لحظةُ الإقلاعِ الذي أخذَ الاسمَ: تُقرأُ عندَ الرفضِ لبيانِ عمرَ الحيازةِ.';
COMMENT ON COLUMN state.worker_registrations.heartbeat_at IS
  'آخرُ نبضةٍ من المالكِ الحاليّ: تقادُمُها فوقَ العتبةِ يفتحُ الاسمَ لإقلاعٍ جديدٍ بأخذٍ ذرّيٍّ لا بفحصٍ عابرٍ.';
