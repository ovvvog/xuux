-- تراجع الهجرة 0010.
--
-- **يُعيد الحالَ إلى سجلٍّ واحدٍ بلا قنوات بإعلانه:** بسقوط الجدولين يعود القارئ
-- إلى ترشيح السجل كلّه بيده وبلا موضعِ قراءةٍ محفوظ وبلا تخليصٍ على المجال —
-- ويصير معيارُ القبول «مُنتِجٌ ومستهلكٌ عبر كل قناة» غيرَ محقَّق.
--
-- ومعه تسقط **رسائلُ القنوات ومواضعُ القراءة**: وهذا فقدُ أثرٍ لا استعادةُ حال.
-- ومواضعُ القراءة أخصُّ خطراً: من يُسقطها ثم يُهاجر صعوداً يجد كل مجموعةٍ عند
-- الصفر، فتُعالج كلُّ رسالةٍ في الدولة من جديد كأنها وقعت الآن.
--
-- ولهذا يُشترط تفريغُ جدول الرسائل باليد قبل التراجع: الهجرة **لا تحذف رسائل**.
-- حذفُ رسالةٍ منشورةٍ قرارٌ يُوقَّع لا أثرٌ جانبي لتراجعٍ تقني.

DO $$
DECLARE messages bigint;
BEGIN
  SELECT count(*) INTO messages FROM state.event_messages;

  IF messages > 0 THEN
    RAISE EXCEPTION
      'تراجع الهجرة 0010 موقوف: القنوات تحمل % رسالة. إسقاط الجدول يمحو أثر أحداثٍ وقعت، ويُعيد كل مجموعة استهلاك إلى الصفر فتُعالج الرسائل كلها من جديد. صدّرها (scripts/backup.mjs) وأفرغها بقرارٍ موقَّع ثم أعِد التراجع.',
      messages;
  END IF;
END $$;

DROP TABLE state.event_offsets;

DROP TABLE state.event_messages;
