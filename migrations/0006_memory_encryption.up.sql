-- 0006 — مادة الذاكرة لا تُخزَّن نصّاً (الخطوة M7.03)
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ما كان: عمود `state.memories.content` يحمل `{"value": ...}` نصّاً صريحاً.
-- فالتخليص الأمني (M7.02) يمنع القراءة من خلال الكود، ومن قرأ القاعدة من غير
-- طريق الكود — `psql` بحساب صيانة، نسخة احتياطية منسوخة، قرصٌ مُصادَر — قرأ
-- المادة كما هي. الحماية كانت في المسار لا في المادة.
--
-- وما صار: العمود يحمل **غلافاً مصادقاً** (AES-256-GCM) بمفتاح مرتبةٍ مقيمٍ في
-- مزوّد المفاتيح خارج القاعدة. والقيد هنا هو ما يجعل الشرط قائماً **ولو كُتب
-- الصفّ من غير طريق الكود**: كتابةٌ مباشرة بمادةٍ نصّية تُرفض في القاعدة نفسها.
--
-- ولماذا القيد غير مشروط بالتصنيف: التصنيف يسكن `state.data_assets` لا هذا
-- الجدول، وقيدُ `CHECK` لا يقرأ جدولاً آخر. ونسخُ عمود التصنيف هنا هو بعينه
-- انحراف «الحقيقة الواحدة في موضعين» الذي أُصلح في M7.01. فالقرار المُعلَن:
-- محتوى ذاكرة وكيل ليس مادةً عامّة ويُغلَّف دائماً — فيصير القيد يحرس نفسه.
--
-- ومنعُ `value` مقصود: غلافٌ يجاوره حقلُ نصٍّ صريح هو أسوأ الحالتين، لأنه يُقرأ
-- كأنّ التشفير قائم والمادة مكشوفة بجانبه.

-- ولا `BEGIN`/`COMMIT` هنا: المُهاجر يفتح المعاملة بنفسه (`withTransaction`)،
-- و`COMMIT` داخل ملف الهجرة كان سيُثبّت المعاملة الخارجية قبل صفّها في
-- `schema_migrations` — أي هجرةٌ مُطبَّقة غير مسجَّلة.

-- صفوفٌ نصّية قائمة لا تُشفَّر هنا: التشفير يحتاج مفاتيح المزوّد، ولا يملكها
-- المُهاجر. وحذفُها صامتاً محوُ بيانات، والمرورُ عنها يجعل القيد كذبة. فالترحيل
-- **يتوقّف** ويقول ما يجب فعله — والفشل المغلق هو المادة 9.
DO $$
DECLARE
  plain_rows bigint;
BEGIN
  SELECT count(*) INTO plain_rows
  FROM state.memories
  WHERE NOT (content ? '__enc');

  IF plain_rows > 0 THEN
    RAISE EXCEPTION
      'الترحيل 0006 متوقّف: % صفّاً في state.memories بمادة نصّية غير مغلَّفة. تغليفُها يحتاج مفاتيح مزوّد المفاتيح ولا يملكها المُهاجر، وحذفُها محوُ بيانات لا ترحيل. غلِّفها بمسار الكود (AgentMemoryStore) ثم أعِد الترحيل.',
      plain_rows;
  END IF;
END $$;

ALTER TABLE state.memories
  ADD CONSTRAINT memories_content_sealed CHECK (
    content ? '__enc'
    AND content ? 'alg'
    AND content ? 'kek'
    AND content ? 'tier'
    AND content ? 'dek'
    AND content ? 'dekIv'
    AND content ? 'dekTag'
    AND content ? 'iv'
    AND content ? 'tag'
    AND content ? 'ct'
    -- المعمّى المصادق وحده؛ ولا حقل `value` بجانبه.
    AND content ->> 'alg' = 'aes-256-gcm'
    AND NOT (content ? 'value')
  );

COMMENT ON COLUMN state.memories.content IS
  'غلاف AES-256-GCM لمادة الذاكرة (M7.03): مفتاح مدخلٍ عشوائي مغلَّف بمفتاح المرتبة المقيم في مزوّد المفاتيح. لا نصّ صريح، ويفرضه القيد memories_content_sealed.';
