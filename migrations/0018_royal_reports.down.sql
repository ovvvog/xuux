-- تراجع الهجرة 0018.
--
-- **يُعيد الحالَ إلى دولةٍ لا تقريرَ لها:** بسقوطِ الجدولِ لا يبقى موضعٌ يُقرأ
-- منه حالُ الدولةِ ومخاطرُها ومخالفاتُها وتكلفتُها في نافذةٍ مُعلَنة، ولا يبقى
-- تمييزٌ محفوظٌ بين رقمٍ قِيس من صفوفٍ ورقمٍ قُدِّر — وهو نفسُه معيارُ قبولِ
-- الخطوة M8.09: «تقريرٌ مُولَّدٌ فعلاً ومُراجَع، بلا حقولٍ تقديريةٍ غيرِ معلَنة».
--
-- وأخطرُ من فقدِ التقاريرِ أنّ محوَها يمحو **المراجعةَ وأمرَ النشر**: تقريرٌ
-- راجعَه بشريٌّ باسمِه وسببِه ثم نُشر بأمرٍ ملكيٍّ معرَّفٍ يصير كأنّه لم يُراجَع
-- ولم يُؤمَر بنشره. فالمساءلةُ التي يُمحى صفُّها مساءلةٌ لا تُطلَب.
--
-- ولذلك يُشترط ألّا يكون في الجدولِ صفٌّ واحد. وصفوفُه **وقائعُ نهائيةٌ** لا
-- تُعاد بالإنفاذ من وثيقة: قياسُ نافذةٍ مضت لا يُعاد بعد أن تغيّرت صفوفُها،
-- ووقتُ مراجعةٍ بشريةٍ ومعرّفُ أمرٍ ملكيٍّ ماضٍ لا يُشتقُّ أيٌّ منهما من
-- `config/royal-reports.yaml`.

DO $$
DECLARE recorded bigint;
BEGIN
  SELECT count(*) FROM state.royal_reports INTO recorded;

  IF recorded > 0 THEN
    RAISE EXCEPTION
      'تراجع الهجرة 0018 موقوف: % تقريراً ملكيّاً مسجَّلاً. إسقاطُ الجدول يمحو قياسَ نوافذَ مضت وبصماتِها ومراجعاتِها البشريةَ وأوامرَ نشرها، ولا يُعاد أيٌّ منها بالإنفاذ من وثيقة. صدّرها (scripts/backup.mjs) ثم أعِد التراجع.',
      recorded;
  END IF;
END $$;

DROP INDEX state.royal_reports_publish_command_idx;
DROP INDEX state.royal_reports_published_period_idx;
DROP INDEX state.royal_reports_state_period_idx;

DROP TABLE state.royal_reports;
