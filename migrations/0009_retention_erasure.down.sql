-- تراجع الهجرة 0009.
--
-- **يُعيد المحوَ بلا شاهدٍ بإعلانه:** بسقوط `state.erasure_records` يعود مسارُ
-- `M3.08` وحده — حذفٌ مباشر بلا سبب ولا فاعل — ويصير معيار «تُمحى وتُسجَّل»
-- غيرَ محقَّق. ومعه تسقط شواهدُ المحو المكتوبة: وهذا **فقدُ دليلٍ لا استعادةُ
-- حال**، فمن يتراجع يُسقط شهادةً على بياناتٍ زالت ولا تعود.
--
-- ولهذا يُشترط تفريغ الدفتر باليد قبل التراجع: الهجرة **لا تحذف شواهد**. حذفُ
-- شاهدٍ قرارٌ يُوقَّع لا أثرٌ جانبي لتراجعٍ تقني.

DO $$
DECLARE witnesses bigint;
BEGIN
  SELECT count(*) INTO witnesses FROM state.erasure_records;

  IF witnesses > 0 THEN
    RAISE EXCEPTION
      'تراجع الهجرة 0009 موقوف: الدفتر يحمل % شاهد محوٍ. إسقاط الجدول يمحو شهادةً على بياناتٍ زالت ولا تعود، وهو فقدُ دليل لا استعادةُ حال. صدّرها (scripts/backup.mjs) وأفرغها بقرارٍ موقَّع ثم أعِد التراجع.',
      witnesses;
  END IF;
END $$;

DROP INDEX state.memories_dataset_idx;

DROP TABLE state.erasure_records;
