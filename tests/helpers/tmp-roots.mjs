/**
 * تسجيلُ الجذورِ المؤقّتةِ لمحوِها عندَ خروجِ العمليّةِ — سياسةُ `LIVE-9`.
 *
 * **علّةُ وجودِ هذه الوحدةِ عَطَبٌ قِيسَ لا خطرٌ مُتخيَّلٌ:** حزمةُ الاختباراتِ
 * كانت تُنشئُ جذوراً مؤقّتةً في `/tmp` **ولا تَحذفُها**. وذلكَ **لا يظهرُ** على
 * عدّاءٍ عابرٍ تُهدَمُ آلتُه بعدَ كلِّ تشغيلةٍ، **ويَقتُلُ** عدّاءً مقيماً يَبقى
 * فيه `/tmp` بينَ التشغيلاتِ: ثلاثةُ ملفّاتٍ تَنسخُ شجرةَ المستودعِ فأنفَدَتِ
 * المساحةَ، فسقطَتْ تشغيلةٌ بـ`125` فشلَ `copyfile` برمزِ `EDQUOT` **بلا علاقةٍ
 * بالشفرةِ** (‏`LIVE-9` / `WL-217`، التشغيلةُ `35334036249`).
 *
 * **ولا يُغلَقُ مثلُ هذا بإصلاحِ الملفّاتِ الثلاثةِ:** الفئةُ تعودُ بأسماءٍ جديدةٍ
 * وملفّاتٍ جديدةٍ. وقد قِيسَ أنّها **قائمةٌ فعلاً** في `29` ملفّاً آخرَ بـ`43`
 * موضعَ إنشاءٍ، تَركَت `39` جذراً و`~51M` في تشغيلةٍ واحدةٍ على `main`
 * (‏`WL-218`) — و`/tmp` هناك قرصٌ ذاكريٌّ سعتُه `788M` فقط، أي **~`14` تشغيلةً
 * حتّى الامتلاءِ**. فما لا يُقاسُ يعودُ، ولذلك صارَ لهذه الوحدةِ **حاجزٌ**
 * (`npm run guard:test-tmp-hygiene`) يَرفضُ ملفَّ اختبارٍ يُنشئُ جذراً ولا
 * يُدبِّرُ محوَهُ — **بلا قائمةِ استثناءٍ**.
 *
 * **ولا تُغيِّرُ هذه الوحدةُ منطقَ اختبارٍ ولا توكيداً:** `registerTmpRoot`
 * تُعيدُ **المسارَ نفسَه** الذي أعطيتَها، فموضعُ النداءِ يُغلَّفُ ولا يُستبدَلُ،
 * ولا يُمَسُّ جسدُ اختبارٍ. والمحوُ يقعُ عندَ **خروجِ العمليّةِ** لا بينَ
 * الاختباراتِ، و`node --test` يُشغِّلُ كلَّ ملفٍّ في عمليّةٍ مستقلّةٍ، فلا يَمحو
 * جذرَ ملفٍّ آخرَ ما زالَ يعملُ.
 *
 * **حدودٌ مُعلَنةٌ لا مستورةٌ:**
 *   1. لا تَبلغُ ما تُنشئُه **عمليّةٌ فرعيّةٌ** يُشعِلُها اختبارٌ — تلكَ تَمحو
 *      لنفسِها أو تَبقى، ويَكشِفُها قياسُ `/tmp` بعدَ الاختباراتِ في CI.
 *   2. المحوُ عندَ الخروجِ **لا يقعُ** إن قُتِلَتِ العمليّةُ بـ`SIGKILL` أو
 *      انهارَتْ — فبقاءُ جذرٍ بعدَ انهيارٍ سلوكٌ متوقَّعٌ لا عَطَبٌ جديدٌ.
 *
 * @module tests/helpers/tmp-roots
 */

import { rmSync } from 'node:fs';
import process from 'node:process';

/** @type {string[]} الجذورُ المُسجَّلةُ في هذه العمليّةِ. */
const ROOTS = [];

/** @type {boolean} هل رُكِّبَ مُستمِعُ الخروجِ؟ — يُركَّبُ مرّةً واحدةً. */
let installed = false;

/**
 * يَمحو كلَّ جذرٍ مُسجَّلٍ. **لا يَرمي**: خروجُ العمليّةِ لا يُفسَدُ بفشلِ محوٍ،
 * وما بقيَ يَكشِفُه قياسُ `/tmp` في CI لا تجاهُلٌ صامتٌ.
 *
 * @returns {void}
 */
function purgeRoots() {
  while (ROOTS.length > 0) {
    const dir = ROOTS.pop();
    try {
      rmSync(String(dir), { recursive: true, force: true });
    } catch {
      // مقصودٌ: الخروجُ لا يُفسَدُ بفشلِ محوٍ.
    }
  }
}

/**
 * يُسجِّلُ جذراً مؤقّتاً لمحوِه عندَ خروجِ العمليّةِ، **ويُعيدُهُ كما هو**.
 *
 * تُستعمَلُ تغليفاً لموضعِ الإنشاءِ لا استبدالاً له:
 *
 * ```js
 * const dir = registerTmpRoot(fs.mkdtempSync(path.join(os.tmpdir(), 'x-')));
 * ```
 *
 * @param {string} dir مسارُ الجذرِ المُنشَأِ.
 * @returns {string} المسارُ نفسُه بلا تغييرٍ.
 */
export function registerTmpRoot(dir) {
  const value = String(dir);
  if (!installed) {
    process.on('exit', purgeRoots);
    installed = true;
  }
  ROOTS.push(value);
  return value;
}

/**
 * الجذورُ المُسجَّلةُ الآنَ — **موجودةٌ ليُقاسَ السلوكُ لا ليُغيَّرَ**: بها يُثبَتُ
 * في اختبارِ الحاجزِ أنّ التسجيلَ يقعُ فعلاً وأنّ المحوَ يُصيبُ ما سُجِّلَ.
 *
 * @returns {string[]} نسخةٌ من قائمةِ الجذورِ.
 */
export function registeredTmpRoots() {
  return [...ROOTS];
}
